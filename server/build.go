package main

import (
	"errors"
	"fmt"
	"html/template"
	"io"
	"io/fs"
	"log"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// marker names the file that identifies a directory as generated output, so
// that build refuses to wipe a directory it did not create.
const marker = ".generated-by-webserver"

// maxFileSize is Cloudflare's per-asset limit (25 MiB). Bigger files are left
// out of the static build and reported, since the deploy would be rejected.
const maxFileSize = 25 * 1024 * 1024

// build writes the whole site as static files into out: a rendered
// index.html for every URL the server would answer, copies of every other
// file, the feeds, sitemaps, robots.txt, a 404 page and the /pub/ assets.
func (s *Server) build(out string) error {
	out, err := filepath.Abs(out)
	if err != nil {
		return err
	}
	if out == s.rootResolved || strings.HasPrefix(out, s.rootResolved+string(filepath.Separator)) ||
		strings.HasPrefix(s.rootResolved, out+string(filepath.Separator)) {
		return fmt.Errorf("build directory %s must be outside the site directory %s", out, s.root)
	}
	if err := prepareOutDir(out); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(out, marker), []byte("This directory is generated by server/webserver -build; do not edit.\n"), 0o644); err != nil {
		return err
	}

	var stats struct{ pages, files int }
	var skipped []string
	write := func(rel string, data []byte) error {
		dst := filepath.Join(out, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return err
		}
		return os.WriteFile(dst, data, 0o644)
	}
	// render handles a URL and writes it as <url>/index.html (for pages) or
	// as the file named by the URL (feeds, sitemaps).
	render := func(url, rel string) error {
		resp := s.handle(url)
		if resp.body == nil {
			return fmt.Errorf("%s: unexpected %+v", url, resp)
		}
		if resp.status != 200 {
			return fmt.Errorf("%s: status %d", url, resp.status)
		}
		stats.pages++
		return write(rel, resp.body)
	}

	visited := map[string]bool{}
	var walk func(rel string) error
	walk = func(rel string) error { // rel is a URL path with trailing slash
		abs := s.localPath(rel)
		real, err := filepath.EvalSymlinks(abs)
		if err != nil || visited[real] {
			return nil
		}
		visited[real] = true
		if err := render(rel, path.Join(rel, "index.html")); err != nil {
			return err
		}
		entries, err := os.ReadDir(abs)
		if err != nil {
			return err
		}
		for _, e := range entries {
			name := e.Name()
			if name == ".git" || forbiddenName(name) {
				continue
			}
			full := filepath.Join(abs, name)
			if !s.inRoot(full) {
				log.Printf("skipping %s: symlink leaves the site directory", full)
				continue
			}
			if isDir(full) {
				if err := walk(rel + name + "/"); err != nil {
					return err
				}
				continue
			}
			if !isFile(full) {
				continue
			}
			stem := strings.TrimSuffix(name, filepath.Ext(name))
			switch {
			case hasPageExt(name) && stem == "index":
				// Rendered as the directory's page above; .md/.txt sources are
				// also copied so they stay readable at their own URL.
				if filepath.Ext(name) != ".html" {
					if err := copyFile(full, filepath.Join(out, filepath.FromSlash(rel), name)); err != nil {
						return err
					}
					stats.files++
				}
			case hasPageExt(name):
				// foo.md -> foo/index.html, unless something called foo already
				// exists next to it (a directory, or a raw file like foo.odt
				// beside foo.odt.md), which keeps its place in the output.
				if _, err := os.Lstat(filepath.Join(abs, stem)); err == nil {
					log.Printf("note: %s%s is shadowed by %s%s in the static output", rel, stem, rel, stem)
				} else if err := render(rel+stem, path.Join(rel, stem, "index.html")); err != nil {
					return err
				}
				if filepath.Ext(name) != ".html" {
					if err := copyFile(full, filepath.Join(out, filepath.FromSlash(rel), name)); err != nil {
						return err
					}
					stats.files++
				}
			default:
				if st, err := os.Stat(full); err == nil && st.Size() > maxFileSize {
					skipped = append(skipped, fmt.Sprintf("%s (%d MiB)", rel+name, st.Size()/1024/1024))
					continue
				}
				if err := copyFile(full, filepath.Join(out, filepath.FromSlash(rel), name)); err != nil {
					return err
				}
				stats.files++
			}
		}
		return nil
	}
	if err := walk("/"); err != nil {
		return err
	}

	// Generated files that have no source of their own.
	for _, blog := range s.blogs {
		for _, f := range []string{"index.rss", "index.atom", "feed.json"} {
			if err := render(blog+f, blog+f); err != nil {
				return err
			}
		}
	}
	if err := render("/sitemap", "/sitemap/index.html"); err != nil {
		return err
	}
	for _, f := range []string{"/sitemap.xml", "/sitemap.txt", "/sitemap.gz", "/robots.txt"} {
		if !s.servable(s.localPath(f)) {
			if err := render(f, f); err != nil {
				return err
			}
		}
	}
	if err := write("/404.html", s.static404()); err != nil {
		return err
	}
	if err := write("/_headers", []byte("/*\n  X-Content-Type-Options: nosniff\n")); err != nil {
		return err
	}
	if err := fs.WalkDir(s.pub, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		data, err := fs.ReadFile(s.pub, p)
		if err != nil {
			return err
		}
		stats.files++
		return write(path.Join("/pub", p), data)
	}); err != nil {
		return err
	}
	log.Printf("built %s: %d pages rendered, %d files copied", out, stats.pages, stats.files)
	for _, f := range skipped {
		log.Printf("warning: left out %s: larger than Cloudflare's 25 MiB asset limit", f)
	}
	return nil
}

// static404 renders the 404 page for static hosting, where the requested URL
// is only known in the browser.
func (s *Server) static404() []byte {
	var sb strings.Builder
	_ = s.notFound.Execute(&sb, map[string]any{"URL": s.baseURL + "/", "Static": true})
	pg := &pageData{ReqPath: "/", PageTitle: "Not found", Body: template.HTML(sb.String())}
	out, err := s.renderPage(pg)
	if err != nil {
		return []byte(err.Error())
	}
	return out
}

// prepareOutDir empties out, refusing to touch a non-empty directory that was
// not produced by a previous build.
func prepareOutDir(out string) error {
	entries, err := os.ReadDir(out)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return os.MkdirAll(out, 0o755)
	case err != nil:
		return err
	}
	if len(entries) > 0 {
		if _, err := os.Stat(filepath.Join(out, marker)); err != nil {
			return fmt.Errorf("%s is not empty and was not created by a previous build; refusing to overwrite it", out)
		}
	}
	for _, e := range entries {
		if err := os.RemoveAll(filepath.Join(out, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func copyFile(src, dst string) error {
	st, err := os.Stat(src)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	outF, err := os.Create(dst)
	if err != nil {
		return err
	}
	if _, err := io.Copy(outF, in); err != nil {
		outF.Close()
		return err
	}
	if err := outF.Close(); err != nil {
		return err
	}
	return os.Chtimes(dst, st.ModTime(), st.ModTime())
}
